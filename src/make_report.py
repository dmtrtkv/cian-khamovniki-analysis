def set_font(run, size=14, bold=False, mono=False, italic=False):
    run.font.name = MONO if mono else FONT
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    for attr in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        rfonts.set(qn(attr), MONO if mono else FONT)
    return run


def para(doc, text="", *, size=14, bold=False, align=None, indent=True,
         spacing=1.5, before=0, after=0, mono=False, italic=False, keep=False):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing = spacing
    pf.first_line_indent = Cm(1.25) if indent else Cm(0)
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.alignment = align if align is not None else WD_ALIGN_PARAGRAPH.JUSTIFY
    if keep:
        pf.keep_with_next = True
    if text:
        set_font(p.add_run(text), size, bold, mono, italic)
    return p


def heading(doc, text, level=1, *, caps=False, page_break=False):
    """Заголовок по макету: без автонумерации, главы — с номером без точки."""
    if page_break:
        doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)
    p = doc.add_paragraph()
    p.style = doc.styles[f"Heading {level}"]
    pf = p.paragraph_format
    pf.line_spacing = 1.5
    pf.first_line_indent = Cm(0) if caps else Cm(1.25)
    pf.space_before = Pt(0)
    pf.space_after = Pt(6)
    pf.alignment = WD_ALIGN_PARAGRAPH.CENTER if caps else WD_ALIGN_PARAGRAPH.LEFT
    pf.keep_with_next = True
    run = p.add_run(text.upper() if caps else text)
    set_font(run, 14, bold=True)
    run.font.color.rgb = RGBColor(0, 0, 0)
    return p


def caption(doc, text, kind):
    """Подпись объекта: «Таблица N – ...» или «Рисунок N – ...», по центру."""
    _counters[kind] += 1
    word = "Таблица" if kind == "tab" else "Рисунок"
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing = 1.5
    pf.first_line_indent = Cm(0)
    pf.space_before = Pt(6 if kind == "tab" else 0)
    pf.space_after = Pt(6 if kind == "fig" else 4)
    pf.alignment = WD_ALIGN_PARAGRAPH.CENTER
    if kind == "tab":
        pf.keep_with_next = True
    set_font(p.add_run(f"{word} {_counters[kind]} – {text}"), 12)
    return _counters[kind]


def picture(doc, name, text, width_cm=16.0):
    """Рисунок по центру, подпись под ним."""
    p = doc.add_paragraph()
    p.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Cm(0)
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(4)
    p.paragraph_format.keep_with_next = True
    p.add_run().add_picture(str(FIG / f"{name}.png"), width=Cm(width_cm))
    return caption(doc, text, "fig")


def listing(doc, code, text):
    """Листинг кода в рамке, оформлен как рисунок (подпись снизу)."""
    tbl = doc.add_table(rows=1, cols=1)
    tbl.style = "Table Grid"
    tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell = tbl.rows[0].cells[0]
    cell.paragraphs[0]._element.getparent().remove(cell.paragraphs[0]._element)
    for line in code.strip("\n").split("\n"):
        p = cell.add_paragraph()
        pf = p.paragraph_format
        pf.line_spacing = 1.0
        pf.first_line_indent = Cm(0)
        pf.space_before = Pt(0)
        pf.space_after = Pt(0)
        pf.alignment = WD_ALIGN_PARAGRAPH.LEFT
        set_font(p.add_run(line if line.strip() else " "), 10, mono=True)
    return caption(doc, text, "fig")


def table(doc, headers, rows, text, widths=None, size=12, head_size=12):
    """Таблица с подписью сверху и шапкой, повторяющейся на новой странице."""
    num = caption(doc, text, "tab")
    tbl = doc.add_table(rows=1, cols=len(headers))
    tbl.style = "Table Grid"
    tbl.alignment = WD_TABLE_ALIGNMENT.CENTER

    for i, h in enumerate(headers):
        cell = tbl.rows[0].cells[i]
        p = cell.paragraphs[0]
        p.paragraph_format.line_spacing = 1.0
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.space_before = Pt(2)
        p.paragraph_format.space_after = Pt(2)
        p.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
        set_font(p.add_run(str(h)), head_size, bold=True)
    # повтор шапки на каждой странице
    trpr = tbl.rows[0]._tr.get_or_add_trPr()
    hdr = OxmlElement("w:tblHeader")
    hdr.set(qn("w:val"), "true")
    trpr.append(hdr)

    for row in rows:
        cells = tbl.add_row().cells
        for i, v in enumerate(row):
            p = cells[i].paragraphs[0]
            p.paragraph_format.line_spacing = 1.0
            p.paragraph_format.first_line_indent = Cm(0)
            p.paragraph_format.space_before = Pt(2)
            p.paragraph_format.space_after = Pt(2)
            p.paragraph_format.alignment = (WD_ALIGN_PARAGRAPH.LEFT if i == 0
                                            else WD_ALIGN_PARAGRAPH.CENTER)
            set_font(p.add_run(str(v)), size)

    if widths:
        for r in tbl.rows:
            for i, w in enumerate(widths):
                r.cells[i].width = Cm(w)
    return num


def field(paragraph, code):
    """Вставка поля Word (PAGE, TOC и т.п.)."""
    r = paragraph.add_run()
    b = OxmlElement("w:fldChar"); b.set(qn("w:fldCharType"), "begin")
    i = OxmlElement("w:instrText"); i.set(qn("xml:space"), "preserve"); i.text = code
    s = OxmlElement("w:fldChar"); s.set(qn("w:fldCharType"), "separate")
    t = OxmlElement("w:t"); t.text = "нажмите F9 для обновления"
    e = OxmlElement("w:fldChar"); e.set(qn("w:fldCharType"), "end")
    for el in (b, i, s, t, e):
        r._element.append(el)
    set_font(r, 14)
    return r


def page_numbers(section):
    """Нумерация страниц в нижнем колонтитуле, по центру."""
    section.footer.is_linked_to_previous = False
    p = section.footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Cm(0)
    field(p, "PAGE")


